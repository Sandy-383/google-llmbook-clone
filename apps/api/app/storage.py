import hashlib
import os
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO


class FileTooLargeError(Exception):
    pass


@dataclass(frozen=True)
class StoredFile:
    key: str
    size_bytes: int
    sha256: str
    head: bytes  # first bytes of the file, for type sniffing


class LocalStorage:
    """Uploaded files on local disk (a Docker volume shared by the API and the worker).

    Keys are generated by the app, never taken from user input, so they can't escape the root.
    """

    HEAD_BYTES = 8192

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"Invalid storage key: {key!r}")
        return path

    def save(self, key: str, stream: BinaryIO, *, max_bytes: int) -> StoredFile:
        """Copy a stream to `key`, hashing as it goes. Writes to a temp file first, so a
        rejected or interrupted upload never leaves a partial file behind."""
        target = self.path(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha256()
        size = 0
        head = b""
        fd, tmp_name = tempfile.mkstemp(dir=target.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as tmp:
                while block := stream.read(1024 * 1024):
                    size += len(block)
                    if size > max_bytes:
                        raise FileTooLargeError
                    if len(head) < self.HEAD_BYTES:
                        head += block[: self.HEAD_BYTES - len(head)]
                    digest.update(block)
                    tmp.write(block)
            os.replace(tmp_name, target)
        except BaseException:
            Path(tmp_name).unlink(missing_ok=True)
            raise
        return StoredFile(key=key, size_bytes=size, sha256=digest.hexdigest(), head=head)

    def read_bytes(self, key: str) -> bytes:
        return self.path(key).read_bytes()

    def delete(self, key: str) -> None:
        self.path(key).unlink(missing_ok=True)

    def delete_tree(self, prefix: str) -> None:
        """Remove everything under `prefix`, e.g. all files of one notebook."""
        path = self.path(prefix)
        if path == self.root:
            raise ValueError("Refusing to delete the storage root")
        shutil.rmtree(path, ignore_errors=True)
